#!/usr/bin/env python3
"""BuildFix27 CP45: deterministic intake validator for an external PS2DEV bundle.

This tool never downloads or modifies the Project Titan source tree. It accepts
an already materialized/extracted PS2DEV environment, validates the target
compilers and the official HDD/PFS IRX chain, and can emit an environment file
for a subsequent target build.
"""
from __future__ import annotations
import argparse
import os
import shlex
import stat
import subprocess
import sys
from pathlib import Path

IRX_REL = (
    Path("iop/irx/ps2atad.irx"),
    Path("iop/irx/ps2hdd.irx"),
    Path("iop/irx/ps2fs.irx"),
)


def executable(path: Path) -> bool:
    return path.is_file() and bool(path.stat().st_mode & stat.S_IXUSR)


def resolve_layout(root: Path) -> tuple[Path, Path]:
    root = root.resolve()
    candidates = [root, root / "ps2dev", root / "usr/local/ps2dev"]
    for ps2dev in candidates:
        sdk_candidates = [ps2dev / "ps2sdk", ps2dev / "sdk", ps2dev / "share/ps2sdk"]
        for sdk in sdk_candidates:
            if (ps2dev / "ee/bin").is_dir() and sdk.is_dir():
                return ps2dev, sdk
    raise ValueError("could not locate PS2DEV/PS2SDK layout under supplied root")


def find_tool(ps2dev: Path, names: tuple[str, ...]) -> Path | None:
    roots = (ps2dev / "ee/bin", ps2dev / "iop/bin", ps2dev / "dvp/bin", ps2dev / "bin")
    for r in roots:
        for name in names:
            p = r / name
            if executable(p):
                return p
    return None


def first_line_version(tool: Path) -> str:
    try:
        cp = subprocess.run([str(tool), "--version"], stdout=subprocess.PIPE, stderr=subprocess.STDOUT,
                            text=True, timeout=5, check=False)
        return (cp.stdout.splitlines() or [f"exit={cp.returncode}"])[0][:200]
    except (OSError, subprocess.TimeoutExpired) as exc:
        return f"unrunnable: {exc}"


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("bundle_root", type=Path)
    ap.add_argument("--emit-env", type=Path)
    ap.add_argument("--require-ready", action="store_true")
    args = ap.parse_args()

    checks: list[tuple[str, bool, str]] = []
    try:
        ps2dev, ps2sdk = resolve_layout(args.bundle_root)
        checks += [("PS2DEV_LAYOUT", True, str(ps2dev)), ("PS2SDK_LAYOUT", True, str(ps2sdk))]
    except ValueError as exc:
        print(f"PS2DEV_LAYOUT: BLOCKED {exc}")
        print("PS2DEV_BUNDLE_READY=0")
        return 2 if args.require_ready else 0

    tools = {
        "EE_GCC": find_tool(ps2dev, ("mips64r5900el-ps2-elf-gcc",)),
        "EE_LD": find_tool(ps2dev, ("mips64r5900el-ps2-elf-ld",)),
        "IOP_GCC": find_tool(ps2dev, ("mipsel-none-elf-gcc", "iop-gcc")),
        "VU_AS": find_tool(ps2dev, ("dvp-as",)),
    }
    for name, tool in tools.items():
        checks.append((name, tool is not None, str(tool) if tool else "<not found>"))

    for rel in IRX_REL:
        p = ps2sdk / rel
        checks.append((rel.name, p.is_file() and p.stat().st_size > 0,
                       f"{p} size={p.stat().st_size}" if p.is_file() else str(p)))

    # Source provenance must at least contain the matching official build units.
    for rel in (Path("iop/dev9/atad/Makefile"), Path("iop/hdd/apa/Makefile"), Path("iop/hdd/pfs/Makefile")):
        p = ps2sdk / rel
        checks.append((f"source:{rel}", p.is_file(), str(p)))

    ready = all(ok for _, ok, _ in checks)
    for name, ok, detail in checks:
        print(f"{name}: {'OK' if ok else 'BLOCKED'} {detail}")
    if tools["EE_GCC"]:
        print("EE_GCC_VERSION=" + first_line_version(tools["EE_GCC"]))
    if tools["IOP_GCC"]:
        print("IOP_GCC_VERSION=" + first_line_version(tools["IOP_GCC"]))
    print("PS2DEV_BUNDLE_READY=" + ("1" if ready else "0"))

    if ready and args.emit_env:
        env = args.emit_env.resolve()
        env.parent.mkdir(parents=True, exist_ok=True)
        path_parts = [ps2dev / "ee/bin", ps2dev / "iop/bin", ps2dev / "dvp/bin", ps2dev / "bin"]
        text = "\n".join([
            "# Generated by BuildFix27 validate_ps2dev_bundle.py; source this file.",
            f"export PS2DEV={shlex.quote(str(ps2dev))}",
            f"export PS2SDK={shlex.quote(str(ps2sdk))}",
            "export PATH=" + shlex.quote(":".join(str(p) for p in path_parts)) + ':"$PATH"',
            "",
        ])
        env.write_text(text, encoding="utf-8")
        os.chmod(env, 0o600)
        print(f"ENV_FILE={env}")

    if args.require_ready and not ready:
        return 2
    return 0

if __name__ == "__main__":
    raise SystemExit(main())
